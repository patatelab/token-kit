// Bundles the pure-JS core and src/main.js into dist/code.js (Figma plugins load one file).
// Core modules only import from each other, so stripping import/export statements is enough.
// --check fails when dist/code.js is out of date.

import { mkdirSync, readFileSync, writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const core = ["config", "sha256", "tokens", "color", "rules", "baseline", "bundle"].map((n) => resolve(here, `../src/core/${n}.mjs`));

const strip = (source) =>
  source
    .replace(/^import\s[\s\S]*?from\s+["'][^"']+["'];\s*$/gm, "")
    .replace(/^export\s+(?=(?:async\s+)?function|const|let|class)/gm, "");

const parts = [...core, resolve(here, "src/main.js")].map((file) => `// ---- ${file.split("/").slice(-2).join("/")}\n${strip(readFileSync(file, "utf8"))}`);
const output = `// AUTO-GENERATED by figma-plugin/build.mjs. Do not edit; edit src/ and run npm run figma:build.\n(function () {\n"use strict";\n${parts.join("\n")}\n})();\n`;

const target = resolve(here, "dist/code.js");
if (process.argv.includes("--check")) {
  let current = null;
  try {
    current = readFileSync(target, "utf8");
  } catch {}
  if (current !== output) {
    console.error("figma-plugin/dist/code.js is stale: run npm run figma:build");
    process.exitCode = 1;
  }
} else {
  mkdirSync(dirname(target), { recursive: true });
  writeFileSync(target, output);
  console.log(`✓ ${target}`);
}
