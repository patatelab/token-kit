// tokens.css: :root custom properties, theme overrides via media query and data-theme selector.

import { cssValue, cssVarName } from "../css-value.mjs";

export default {
  name: "css-variables",
  files({ index, config }) {
    const prefix = config.cssPrefix ?? "";
    const declare = (e) => {
      const v = cssValue(e.value, e.type, e.extensions, prefix);
      return v === null ? null : `  ${cssVarName(e.path, prefix)}: ${v};`;
    };
    const byTheme = new Map();
    for (const e of index.tokens.values()) {
      const line = declare(e);
      if (line) (byTheme.get(e.theme) ?? byTheme.set(e.theme, []).get(e.theme)).push(line);
    }
    let css = `/* AUTO-GENERATED by token-kit. Source: ${config.tokens}. Do not edit. */\n:root {\n${(byTheme.get("light") ?? []).join("\n")}\n}\n`;
    for (const [name, theme] of Object.entries(config.themes ?? {})) {
      const lines = byTheme.get(name);
      if (!lines?.length) continue;
      const body = lines.map((l) => "  " + l).join("\n");
      if (theme.mediaQuery) css += `\n@media ${theme.mediaQuery} {\n  :root:not([data-theme]) {\n${body}\n  }\n}\n`;
      if (theme.selector) css += `\n${theme.selector} {\n${lines.join("\n")}\n}\n`;
    }
    return [{ path: "tokens.css", content: css }];
  },
};
