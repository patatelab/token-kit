// tokens.ts: typed token names and var() helpers for React components.

import { cssVarName } from "../css-value.mjs";

export default {
  name: "typescript",
  files({ index, config }) {
    const prefix = config.cssPrefix ?? "";
    const internal = new Set(config.tiers.filter((t) => t.internal).map((t) => t.name));
    const rows = [...index.tokens.values()]
      .filter((e) => e.theme === "light" && !internal.has(e.tier))
      .map((e) => `  ${JSON.stringify(e.path)}: ${JSON.stringify(`var(${cssVarName(e.path, prefix)})`)},`)
      .sort();
    const content = `// AUTO-GENERATED by token-kit. Do not edit.
// Internal tiers (by default Primitives) are not exposed.

export const tokens = {
${rows.join("\n")}
} as const;

export type TokenName = keyof typeof tokens;

/** CSS var() expression for a token, e.g. style={{ color: token("color.text.default") }}. */
export function token(name: TokenName): string {
  return tokens[name];
}
`;
    return [{ path: "tokens.ts", content }];
  },
};
