// tailwind.theme.css: Tailwind v4 @theme mapping for semantic roles (colors, spacing, radius):
// tokens in tiers that are neither internal nor component families.
// Theme variables get a namespace (config.tailwindNamespace, default "tk") so they never
// shadow the token custom properties they point to: bg-tk-background-default, p-tk-gutter.

import { cssVarName } from "../css-value.mjs";

const NAMESPACES = { color: "color", dimension: null };

export default {
  name: "tailwind-v4",
  files({ index, config }) {
    const prefix = config.cssPrefix ?? "";
    const nsPrefix = config.tailwindNamespace ?? "tk";
    const semantic = new Set(config.tiers.filter((t) => !t.internal && !t.families).map((t) => t.name));
    const lines = [];
    for (const e of index.tokens.values()) {
      if (e.theme !== "light" || !semantic.has(e.tier)) continue;
      const [root] = e.path.split(".");
      let ns = NAMESPACES[e.type];
      if (e.type === "dimension") ns = root === "space" ? "spacing" : root === "radius" ? "radius" : null;
      if (!ns) continue;
      const rest = e.path.split(".").slice(1).join("-");
      lines.push(`  --${ns}-${nsPrefix}-${rest || root}: var(${cssVarName(e.path, prefix)});`);
    }
    return [{ path: "tailwind.theme.css", content: `/* AUTO-GENERATED by token-kit. Do not edit. */\n@theme inline {\n${lines.join("\n")}\n}\n` }];
  },
};
